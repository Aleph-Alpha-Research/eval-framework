"""Specification of the composed German Hendrycks-Math (EllaMind) minerva tasks."""

from typing import Any

import pytest

from eval_framework.benchmarks.hendrycks_math_ellamind import (
    HENDRYCKS_MATH_ELLAMIND_BENCHMARKS,
    mathminerva_de_bpb_olmes,
    mathminerva_de_olmes,
)
from eval_framework.contract import Benchmark
from template_formatting.formatter import (
    BaseFormatter,
    ConcatFormatter,
    Llama3Formatter,
    Message,
    NoStripConcatFormatter,
    Role,
)
from tests.tests_eval_framework.benchmarks.utils import DatasetStub, first_sample
from tests.tests_eval_framework.tasks.benchmarks.utils import assert_benchmark_formatter_hash

# The recorded baselines were generated by the old test at its default 1-shot (the task honours the requested
# count), so we pin the hash at 1-shot to stay byte-identical. Its canonical eval config is 4-shot.
_NUM_FEWSHOT = {
    "MATHMinervaDE_OLMES": 1,
    "MATHMinervaDE_OLMES_NONL": 1,
    "MATHMinervaDE_BPB_OLMES": 1,
}


@pytest.mark.formatter_hash
@pytest.mark.parametrize("formatter_cls", [Llama3Formatter, ConcatFormatter, NoStripConcatFormatter])
@pytest.mark.parametrize("benchmark", HENDRYCKS_MATH_ELLAMIND_BENCHMARKS, ids=lambda b: b.id())
def test_formatter_hash(benchmark: Benchmark, formatter_cls: type[BaseFormatter]) -> None:
    assert_benchmark_formatter_hash(benchmark, formatter_cls, num_fewshot=_NUM_FEWSHOT[benchmark.id()])


# ---------------------------------------------------------------------------
# Offline prompt spec (fictional rows)
# ---------------------------------------------------------------------------

_EVAL_ROW: dict[str, Any] = {
    "problem": "Was ist 2 + 2?",
    "solution": "Die Antwort ist \\boxed{4}.",
    "extracted_answer": "4",
}
_FEWSHOT_ROW: dict[str, Any] = {
    "problem": "Was ist 3 + 3?",
    "solution": "Die Antwort ist \\boxed{6}.",
    "extracted_answer": "6",
}
_FEWSHOT_TARGET = (
    "Lösung: Die Antwort ist \\boxed{6}.\n"
    "Finale Antwort: Die finale Antwort lautet $6$. Ich hoffe, die Antwort ist korrekt."
)


def test_de_olmes_zeroshot_prompt() -> None:
    benchmark = mathminerva_de_olmes(dataset=DatasetStub({"test": [_EVAL_ROW]}))
    sample = first_sample(benchmark, num_fewshot=0, custom_subjects=["deu"])
    assert sample.messages == [
        Message(role=Role.USER, content="Aufgabe:\nWas ist 2 + 2?\n\n"),
        Message(role=Role.ASSISTANT, content="Lösung:"),
    ]
    assert sample.ground_truth == "4"  # normalized gold from the boxed solution
    assert sample.possible_completions is None  # free-form generation


def test_de_olmes_oneshot_renders_german_final_answer() -> None:
    # Two single-paragraph rows: the sampler shows the other row as the one demonstration.
    benchmark = mathminerva_de_olmes(dataset=DatasetStub({"test": [_FEWSHOT_ROW, _EVAL_ROW]}))
    sample = first_sample(benchmark, num_fewshot=1, custom_subjects=["deu"])
    assert sample.messages == [
        Message(role=Role.USER, content="Aufgabe:\nWas ist 3 + 3?\n\n"),
        Message(role=Role.ASSISTANT, content=_FEWSHOT_TARGET),
        Message(role=Role.USER, content="Aufgabe:\nWas ist 2 + 2?\n\n"),
        Message(role=Role.ASSISTANT, content="Lösung:"),
    ]


def test_de_bpb_scores_single_gold_solution() -> None:
    benchmark = mathminerva_de_bpb_olmes(dataset=DatasetStub({"test": [_EVAL_ROW]}))
    sample = first_sample(benchmark, num_fewshot=0, custom_subjects=["deu"])
    gold = (
        " Die Antwort ist \\boxed{4}.\n"
        "Finale Antwort: Die finale Antwort lautet $4$. Ich hoffe, die Antwort ist korrekt."
    )
    # Prompt matches the generative variant; BPB scores the loglikelihood of the one gold solution.
    assert sample.messages[-1] == Message(role=Role.ASSISTANT, content="Lösung:")
    assert sample.messages[0] == Message(role=Role.USER, content="Aufgabe:\nWas ist 2 + 2?\n\n")
    assert sample.possible_completions == [gold]
    assert sample.ground_truth == gold
